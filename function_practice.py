def square(n):
    return n*n

def cube(n):
    return n*n*n

def doubleNumber(n):
    return n*2

def calc():
    area_of_square= square(5)
    area_of_cube = cube(5)
    doubleNo = doubleNumber(5)
    print(f"area of square = {area_of_square} \n" f" area of cube = {area_of_cube} \n"f" double the number = {doubleNo}")
calc()